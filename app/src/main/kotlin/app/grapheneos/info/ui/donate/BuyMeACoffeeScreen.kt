@Composable
fun BuyMeACoffeeScreen(
    modifier: Modifier = Modifier,
    showSnackbarError: (String) -> Unit = {},
    additionalContentPadding: PaddingValues = PaddingValues(0.dp)
) {
    ScreenLazyColumn(
        modifier = modifier
            .fillMaxSize(),
        additionalContentPadding = additionalContentPadding
    ) {
        item {
            Text(stringResource(R.string.buy_me_a_coffee_description))
        }
        item {
            LinkCardItem(
                imageVector = Icons.Filled.LocalCafe,
                title = stringResource(R.string.buy_me_a_coffee),
                link = "https://buymeacoffee.com/mosaicos",
                showSnackbarError = showSnackbarError
            )
        }
    }
}

